async page => {
  await page.setViewportSize({width:1440,height:1000});
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const button = name => page.getByRole("button", {name, exact:true});
  const collect = () => button("Mark collected for Cometeer");
  const undo = () => button("Undo collection for Cometeer");
  const search = page.getByRole("searchbox", {name:"Search packages"});
  const pending = async () => {
    const hold = {};
    page.__collectionQueue.push(hold);
    await collect().click();
    for (let i=0; i<50 && !hold.started; i++) await page.waitForTimeout(20);
    check(hold.started, "Collection request started");
    check(await collect().isDisabled(), "Pending collection cannot be repeated");
    check(await collect().getAttribute("aria-busy") === "true", "Pending collection is announced");
    check(await collect().textContent().then(t => t.includes("Saving")), "Pending feedback visible");
    return hold;
  };
  await page.evaluate(() => localStorage.clear());
  await page.goto("http://127.0.0.1:4328/");
  await button("All packages").click();
  check(await page.locator(".shipment-entry").filter({hasText:"Schoolhouse"}).getByRole("button", {name:/Mark collected/}).count() === 0, "Active packages cannot be collected");
  await button("Delivered").click();
  await search.fill("CDL coffee");
  const hold = await pending();
  check(await page.getByRole("dialog").count() === 0, "Card action leaves detail closed");
  await page.screenshot({path:"output/playwright/collection-pending-desktop.png",fullPage:true});
  await hold.release();
  await undo().waitFor();
  check(await page.getByText("Collected by Sample member", {exact:true}).count() === 1, "Collector attribution appears");
  check(await search.inputValue() === "CDL coffee", "Collection preserves search");
  check(await button("Delivered").getAttribute("aria-pressed") === "true", "Collection preserves filter");
  const saved = page.__packageFixtures.get("synthetic-household").find(s => s.id === "delivered");
  check(saved.status === "delivered" && saved.deliveredAt, "Collection keeps delivery evidence");
  await page.screenshot({path:"output/playwright/collection-collected-desktop.png",fullPage:true});
  await undo().click();
  await collect().waitFor();
  check(await page.getByText("Collected by Sample member", {exact:true}).count() === 0, "Undo clears attribution");

  await page.setViewportSize({width:390,height:844});
  const failure = await pending();
  await failure.release(500);
  await page.getByRole("alert").filter({hasText:"Synthetic collection failure"}).waitFor();
  check(await collect().isEnabled(), "Failed action can be retried");
  check(!saved.collectedAt, "Failure leaves package uncollected");
  await page.screenshot({path:"output/playwright/collection-failed-mobile.png",fullPage:true});
  await button("To collect").click();
  await collect().click();
  await page.locator(".shipment-list h3").waitFor({state:"detached"});
  check(await button("To collect").getAttribute("aria-pressed") === "true", "Completed To collect filter remains selected");
  check(await search.inputValue() === "CDL coffee", "Completed To collect filter retains search");
  await page.screenshot({path:"output/playwright/collection-complete-mobile.png",fullPage:true});
  await button("Delivered").click();
  await undo().waitFor();
  check((await undo().boundingBox()).height >= 44, "Collection touch target is at least 44px");
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Collection action has no mobile overflow");
  await page.screenshot({path:"output/playwright/collection-collected-mobile.png",fullPage:true});
  await undo().click();
  await collect().waitFor();
  await page.locator(".shipment-card").filter({hasText:"Cometeer"}).click();
  await page.getByRole("dialog").waitFor();
  await page.getByRole("dialog").getByRole("button", {name:"Mark collected",exact:true}).waitFor();
  await button("Close dialog").click();
  await button("To collect").click();
  await collect().waitFor();
  return {passed:true, scenarios:["visible collect and undo", "pending feedback", "error and retry", "delivery preserved", "collector attribution", "To collect updates without navigation", "search/filter preserved", "detail navigation", "390px mobile layout"], syntheticWrites:page.__preferenceWrites};
}
